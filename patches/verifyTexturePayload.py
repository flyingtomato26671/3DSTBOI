import argparse
import hashlib
import re
import subprocess
from pathlib import Path

PayloadBase = 0x2E6200
StorageEnd = 0x2E7000
Reference = "LLVM 22.1.8"
Symbols = [
    ("textureUploadAddress", "UploadTexels"),
    ("textureBindAddress", "BindTexture"),
    ("textureScratchAddress", "AllocateProceduralScratch"),
    ("texturePixelReadAddress", "ReadPixel"),
    ("texturePixelWriteAddress", "WritePixel"),
    ("textureDitherAddress", "DitherStrength"),
]


def BuildPayload(patchPath, outputPath):
    outputPath.mkdir(parents=True, exist_ok=True)
    objectPath = outputPath / "texture16.o"
    elfPath = outputPath / "texture16.elf"
    binaryPath = outputPath / "texture16.bin"
    commands = [
        ["clang++", "--target=arm-none-eabi", "-march=armv6k", "-marm", "-mfpu=vfp",
         "-mfloat-abi=softfp", "-Oz", "-std=c++17", "-ffreestanding", "-fno-exceptions",
         "-fno-rtti", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-c",
         str(patchPath / "Texture16.cpp"), "-o", str(objectPath)],
        ["ld.lld", "-T", str(patchPath / "texture16.ld"), str(objectPath), "-o", str(elfPath)],
        ["llvm-objcopy", "-O", "binary", str(elfPath), str(binaryPath)],
    ]
    for command in commands:
        subprocess.run(command, check=True)

    symbolText = subprocess.check_output(["llvm-nm", "-n", str(elfPath)], text=True)
    (outputPath / "texture16.symbols").write_text(symbolText)
    addresses = {}
    for line in symbolText.splitlines():
        parts = line.split()
        if len(parts) == 3:
            addresses[parts[2]] = int(parts[0], 16)

    payload = binaryPath.read_bytes()
    if PayloadBase + len(payload) > StorageEnd:
        raise RuntimeError("The payload no longer fits the zeroed text padding below 0x2E7000")

    for _, symbol in Symbols:
        if symbol not in addresses:
            raise RuntimeError("Missing payload symbol: " + symbol)

    return payload, addresses


def FormatHeader(payload, addresses):
    digest = hashlib.sha256(payload).hexdigest()
    hexText = payload.hex()
    lines = ['        "' + hexText[index:index + 96] + '"' for index in range(0, len(hexText), 96)]
    text = "#pragma once\n\n#include <cstdint>\n#include <string>\n\n"
    text += "// Generated by patches/verifyTexturePayload.py --update. Do not edit by hand.\n"
    text += "namespace Isaac3ds {\n"
    text += "    inline constexpr std::uint32_t texturePayloadBase = 0x%X;\n" % PayloadBase
    for name, symbol in Symbols:
        text += "    inline constexpr std::uint32_t %s = 0x%X;\n" % (name, addresses[symbol])

    text += '    inline const std::string texturePayloadHash = "%s";\n' % digest
    text += "    inline const std::string texturePayloadHex =\n" + "\n".join(lines) + ";\n}\n"
    return text


def VerifyTexturePayload():
    parser = argparse.ArgumentParser(description="Compile the authored ARM source and compare it with the embedded payload")
    parser.add_argument("--output", type=Path, default=Path("build/payload"))
    parser.add_argument("--update", action="store_true", help="rewrite src/TextureData.h from the compiled payload")
    arguments = parser.parse_args()
    projectPath = Path(__file__).resolve().parents[1]
    patchPath = projectPath / "patches"
    payload, addresses = BuildPayload(patchPath, arguments.output.resolve())
    headerPath = projectPath / "src/TextureData.h"
    expectedHeader = FormatHeader(payload, addresses)
    if arguments.update:
        headerPath.write_text(expectedHeader)
        print("Updated src/TextureData.h")
    elif headerPath.read_text() != expectedHeader:
        raise RuntimeError("Compiler output or symbol addresses differ from src/TextureData.h. The reference used " + Reference +
                           "; rerun with --update only after revalidating the patch profile.")

    rebuildText = (projectPath / "src/RebuildData.h").read_text()
    for name in ["isaac-old80.rsf", "manual.rsf"]:
        if (patchPath / name).read_text() not in rebuildText:
            raise RuntimeError("Embedded rebuild settings differ from " + name)

    print("Authored payload reproduced: " + str(len(payload)) + " bytes, SHA-256 " + hashlib.sha256(payload).hexdigest())


if __name__ == "__main__":
    VerifyTexturePayload()
